/** Раздел на нужном языке. Ссылки (URL) и дата проверки — из русской версии без изменений. */
export function localizeEntry(e: KnowledgeEntry, lang: KnowledgeLang) {
  if (lang === "ru") {
    const { title, steps, documents, timing, notes, links, checkedAt } = e;
    return { title, steps, documents, timing, notes, links, checkedAt };
  }
  const t = e.kk;
  return {
    title: t.title,
    steps: t.steps,
    documents: t.documents,
    timing: t.timing,
    notes: t.notes,
    links: e.links.map((l, i) => ({ title: t.linkTitles[i] ?? l.title, url: l.url })),
    checkedAt: e.checkedAt,
  };
}

export function isFilled(e: { steps: string[]; documents: string[]; timing: string }): boolean {
  return e.steps.length > 0 || e.documents.length > 0 || e.timing.trim() !== "";
}
